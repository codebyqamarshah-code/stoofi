const TeacherEvaluation = require('../models/TeacherEvaluation');

exports.getAll = async (req, res) => {
  try {
    const filter = {};
    if (req.query.status) {
      filter.status = new RegExp(`^${req.query.status}$`, 'i');
    }
    if (req.query.teacherName) {
      filter.teacherName = new RegExp(req.query.teacherName, 'i');
    }
    const data = await TeacherEvaluation.find(filter).sort({ createdAt: -1 });
    res.status(200).json({ success: true, data });
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
};

exports.create = async (req, res) => {
  try {
    const data = await TeacherEvaluation.create(req.body);
    res.status(201).json({ success: true, data });
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
};

exports.update = async (req, res) => {
  try {
    const data = await TeacherEvaluation.findByIdAndUpdate(req.params.id, req.body, { new: true });
    if (!data) return res.status(404).json({ success: false, message: 'Not found' });
    res.status(200).json({ success: true, data });
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
};

exports.remove = async (req, res) => {
  try {
    const data = await TeacherEvaluation.findByIdAndDelete(req.params.id);
    if (!data) return res.status(404).json({ success: false, message: 'Not found' });
    res.status(200).json({ success: true, data: {} });
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
};
